-- Select the project database.
USE cyberguard_meddicc;

-- Store healthcare visits, preserving source identifiers and timestamps.
CREATE TABLE IF NOT EXISTS encounters (
    Id VARCHAR(36) PRIMARY KEY,
    START VARCHAR(30),
    STOP VARCHAR(30),
    PATIENT VARCHAR(36),
    ORGANIZATION VARCHAR(36),
    PROVIDER VARCHAR(36),
    PAYER VARCHAR(36),
    ENCOUNTERCLASS VARCHAR(50),
    CODE VARCHAR(50),
    DESCRIPTION TEXT,
    BASE_ENCOUNTER_COST DECIMAL(15, 2),
    TOTAL_CLAIM_COST DECIMAL(15, 2),
    PAYER_COVERAGE DECIMAL(15, 2),
    REASONCODE VARCHAR(50),
    REASONDESCRIPTION TEXT
);

-- List the tables in the project database.
SHOW TABLES;
-- Confirm that the imported row count matches the source csv
SELECT COUNT(*) AS encounter_rows
FROM cyberguard_meddicc.encounters;

-- Store source claims, preserving identifiers, dates, and recorded balances.
CREATE TABLE IF NOT EXISTS cyberguard_meddicc.claims (
    Id VARCHAR(36) PRIMARY KEY,
    PATIENTID VARCHAR(36),
    PROVIDERID VARCHAR(36),
    PRIMARYPATIENTINSURANCEID VARCHAR(36),
    SECONDARYPATIENTINSURANCEID VARCHAR(36),
    DEPARTMENTID VARCHAR(50),
    PATIENTDEPARTMENTID VARCHAR(50),
    DIAGNOSIS1 VARCHAR(50),
    DIAGNOSIS2 VARCHAR(50),
    DIAGNOSIS3 VARCHAR(50),
    DIAGNOSIS4 VARCHAR(50),
    DIAGNOSIS5 VARCHAR(50),
    DIAGNOSIS6 VARCHAR(50),
    DIAGNOSIS7 VARCHAR(50),
    DIAGNOSIS8 VARCHAR(50),
    REFERRINGPROVIDERID VARCHAR(36),
    APPOINTMENTID VARCHAR(36),
    CURRENTILLNESSDATE VARCHAR(30),
    SERVICEDATE VARCHAR(30),
    SUPERVISINGPROVIDERID VARCHAR(36),
    STATUS1 VARCHAR(50),
    STATUS2 VARCHAR(50),
    STATUSP VARCHAR(50),
    OUTSTANDING1 DECIMAL(15, 2),
    OUTSTANDING2 DECIMAL(15, 2),
    OUTSTANDINGP DECIMAL(15, 2),
    LASTBILLEDDATE1 VARCHAR(30),
    LASTBILLEDDATE2 VARCHAR(30),
    LASTBILLEDDATEP VARCHAR(30),
    HEALTHCARECLAIMTYPEID1 VARCHAR(50),
    HEALTHCARECLAIMTYPEID2 VARCHAR(50)
);
-- Confirm that all source claims were loaded
SELECT COUNT(*) AS claim_rows
FROM cyberguard_meddicc.claims;